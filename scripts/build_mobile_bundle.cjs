const fs = require('node:fs');
const path = require('node:path');
const {execFileSync}=require('node:child_process');
const {sourceHash,inventory}=require('./mobile_bundle_contract.cjs');
const root=process.cwd();
if(!fs.existsSync('capacitor.config.ts')) throw Error('MOBILE_CONFIG_MISSING');
const api=new URL(process.env.SITON_API_BASE_URL || 'https://api.siton.invalid');
if(api.protocol!=='https:' || api.username || api.password || api.pathname!=='/' || api.search || api.hash || ['localhost','127.0.0.1','[::1]'].includes(api.hostname)) throw Error('MOBILE_API_REQUIRES_HTTPS_ORIGIN');
const host=process.env.SITON_APP_LINK_HOST || 'app.siton.invalid';
if(!/^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}$/.test(host)) throw Error('MOBILE_LINK_HOST_INVALID');
// Invoke locked local tools; Vite empties its output. Never consume a pre-existing hosted bundle.
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','-b'],{cwd:path.join(root,'web'),stdio:'inherit'});
execFileSync(process.execPath,['node_modules/vite/bin/vite.js','build','--mode','mobile'],{cwd:path.join(root,'web'),stdio:'inherit'});
const output=path.resolve(root,'.mobile_dist');
if(path.dirname(output)!==root || path.basename(output)!=='.mobile_dist') throw Error('MOBILE_OUTPUT_OUTSIDE_WORKSPACE');
fs.rmSync(output,{recursive:true,force:true});
fs.mkdirSync(output);
fs.cpSync('web/dist',path.join(output,'preview'),{recursive:true});
fs.copyFileSync('mobile/runtime.js',path.join(output,'mobile-runtime.js'));
fs.writeFileSync(path.join(output,'mobile-config.js'),'globalThis.SitonNativeConfig = Object.freeze('+JSON.stringify({apiOrigin:api.origin,linkHost:host})+');\n');
let index=fs.readFileSync(path.join(output,'preview/index.html'),'utf8');
index=index.replace('<head>','<head>\n    <script src="/mobile-config.js"></script>\n    <script src="/mobile-runtime.js"></script>');
fs.writeFileSync(path.join(output,'preview/index.html'),index);
fs.writeFileSync(path.join(output,'index.html'),index);
const manifest={schema_version:2,source:'web/',source_sha256:sourceHash(),api_origin:api.origin,app_link_host:host,placeholder_configuration:api.hostname.endsWith('.invalid')||host.endsWith('.invalid'),files:inventory(output)};
fs.writeFileSync(path.join(output,'mobile-build.json'),JSON.stringify(manifest,null,2)+'\n');
console.log('MOBILE_BUNDLE_READY canonical=web/ start=/preview/ placeholder='+manifest.placeholder_configuration);
